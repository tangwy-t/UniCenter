func TestGenPackageInlinesEmbeddedFields(t *testing.T) {
	dir := t.TempDir()
	writeSample(t, dir, "dept.go", `package response

// Base 基础字段。
type Base struct {
	ID   uint64 `+"`json:\"id,string\"`"+`
	Name string `+"`json:\"name\"`"+`
}

// DeptResp 部门详情(内嵌 Base)。
type DeptResp struct {
	Base
	Parent uint64 `+"`json:\"parent,string\"`"+`
}
`)
	got, err := genPackage(dir)
	if err != nil {
		t.Fatalf("genPackage: %v", err)
	}
	wantDeps := `  namespace System {
    interface Base {
      id: string
      name: string
    }

    interface DeptResp {
      id: string
      name: string
      parent: string
    }
  }
`
	if !contains(got, wantDeps) {
		t.Fatalf("embedded fields not inlined\n--- got ---\n%s\n--- want ---\n%s", got, wantDeps)
	}
}

func contains(s, sub string) bool {
	return len(sub) == 0 || (len(s) >= len(sub) && indexOf(s, sub) >= 0)
}

func indexOf(s, sub string) int {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return i
		}
	}
	return -1
}

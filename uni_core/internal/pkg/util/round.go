package util

import "math"

// Round2 把浮点数量化到 2 位小数,是监控类指标(服务器监控、SQL 监控)
// 对外输出的统一精度约定:所有耗时/百分比/QPS 等派生值在离开计算层前
// 都应经过它,避免 API 响应与前端 tooltip 出现长尾小数。
//
// 为什么需要它:原始采样值即使已经是 2 位小数,一旦参与求平均、加权平均
// 或分位数插值,就会重新产生长尾(如 (1.23+1.23+1.24)/3 = 1.2333333333333334,
// 纳秒换算 float64(ns)/1e6 = 2.345678)。
//
// 实现用 math.Round 而非 int(v*100+0.5) 截断:后者在 .005 这类精确边界上
// 会因二进制浮点表示误差(如 80.005*100 = 8000.49999...)向下错舍;
// math.Round 的语义是 nearest-half-away-from-zero,边界行为更稳定。
// 同时它是单调的:a <= b 必然 round2(a) <= round2(b),因此对已排序序列
// 逐值量化不会破坏 p50 <= p95 <= p99 <= max 的顺序关系。
func Round2(v float64) float64 {
	return math.Round(v*100) / 100
}
